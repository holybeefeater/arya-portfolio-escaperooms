"""Write src/shoot-sizes.js: for every image in public/assets/shoot/, its width,
its height and, for cut-outs, which edges the figure runs into (the photograph's
own crop: legs cut off at the bottom, a shoulder at the side). The page fades
those edges out, so a cut-out never ends on a hard line. Run after
scripts/escape-media.py."""
import os
import numpy as np
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'public', 'assets', 'shoot')

def edges(im):
    a = np.asarray(im.getchannel('A')) > 128
    out = ''
    for k, line in (('t', a[0]), ('r', a[:, -1]), ('b', a[-1]), ('l', a[:, 0])):
        if line.mean() > 0.12:
            out += k
    return out

rows = []
for f in sorted(os.listdir(D)):
    if f.endswith('.webp'):
        im = Image.open(os.path.join(D, f))
        e = edges(im) if im.mode == 'RGBA' else ''
        rows.append(f"  '{f[:-5]}': [{im.width}, {im.height}{', ' + repr(e) if e else ''}],")
open(os.path.join(ROOT, 'src', 'shoot-sizes.js'), 'w').write(
    '// Generated by scripts/shoot-sizes.py: [width, height, edges a cut-out runs into]\n'
    'export default {\n' + '\n'.join(rows) + '\n}\n')
print(len(rows), 'images')
